import { readFileSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { inventory } from "./reflection-inventory.mjs";

const { tools, reflection } = inventory();
const plan = readFileSync(new URL("../docs/harness-tool-policy.md", import.meta.url), "utf8");
const rows = plan.split("\n").filter(line => /^\| MCP-\d+ /.test(line));
const catalog = new Map(tools.map(([id, , name]) => [id, name]));
const items = rows.map(row => {
  const match = row.match(/^\| (MCP-\d+) \| (\w+) \| (reflect|read|mutate) \| (allow|ask|deny) \| (.*) \|$/);
  assert(match, "Invalid policy row");
  const [, id, name, tier, permission, description] = match;
  assert.equal(catalog.get(id), name);
  assert(tier !== "mutate" || permission !== "allow", "Mutations must never be auto-approved");
  catalog.delete(id);
  return { name, tier, permission, description };
});
assert.equal(catalog.size, 0);
const floor = reflection.filter(([, , path]) => /^\/api\/v1\/introspect\/(?:prompts\/|wallet\/(?:signer\.ts$|signers\/))/.test(path))
  .map(([, , path]) => "introspect_" + path.slice("/api/v1/introspect/".length).replace(/[^a-z0-9]+/g, "_"));
assert.equal(floor.length, 13);
assert(!items.some(item => floor.includes(item.name) || item.name === "read_key_source"));
const contents = "// Generated by scripts/generate-harness-policy.mjs.\n" +
  "export const harnessPlan = [\n" + items.map(item => "  " + JSON.stringify(item)).join(",\n") +
  "\n] as const;\n\nexport const hardFloor = " + JSON.stringify([...floor, "read_key_source"]) + " as const;\n";
const out = new URL("../src/harness/catalog.generated.ts", import.meta.url);
const descriptions = "# Model-facing read tool descriptions\n\nGenerated from Table A in [the tool policy](./harness-tool-policy.md). The runtime uses the same descriptions for registered model reads. The manifest includes planned tools.\n\n" +
  items.filter(item => item.permission === "allow").map(item => "## `" + item.name + "`\n\n" + item.description).join("\n\n") + "\n";
const files = [[out, contents], [new URL("../docs/harness-tool-descriptions.md", import.meta.url), descriptions]];
for (const [path, value] of files) {
  if (process.argv.includes("--check")) assert.equal(readFileSync(path, "utf8"), value);
  else writeFileSync(path, value);
}
