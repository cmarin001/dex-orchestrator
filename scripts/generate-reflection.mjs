import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, posix } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { inventory } from "./reflection-inventory.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" });
const revision = "1a457ad029c9eaa57736566863d0962ff12707b4";
const timestamp = git("show", "-s", "--format=%cI", revision).trim();
const { files, reflection } = inventory();
const routes = new Map(reflection.map(([, id, route]) => [id, route]));
const protectedPath = path => /^(src\/wallet\/(signer\.ts$|signers\/)|prompts\/)/.test(path);
const paths = new Set(files.map(([, path]) => path));
const filesByPath = new Map();

function declareExports(source, path) {
  if (!source) return [];
  const printer = ts.createPrinter({ removeComments: true });
  return source.statements.flatMap(node => {
    if (ts.isExportDeclaration(node) || ts.isExportAssignment(node)) {
      const names = node.exportClause && ts.isNamedExports(node.exportClause)
        ? node.exportClause.elements.map(item => item.name.text)
        : [node.exportClause?.name?.text ?? (ts.isExportAssignment(node) ? "default" : "*")];
      return names.map(name => ({ name, kind: "re-export", signature: null }));
    }
    if (!node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) return [];
    const isDefault = node.modifiers.some(modifier => modifier.kind === ts.SyntaxKind.DefaultKeyword);
    const renderType = type => type ? printer.printNode(ts.EmitHint.Unspecified, type, source) : "unknown";
    const signatureFor = (parameters, type) => "(" + parameters.map((parameter, index) =>
      `${parameter.dotDotDotToken ? "..." : ""}${ts.isIdentifier(parameter.name) ? parameter.name.text : "arg" + (index + 1)}${parameter.questionToken || parameter.initializer ? "?" : ""}: ${renderType(parameter.type)}`).join(", ") + "): " + renderType(type);
    if (ts.isFunctionDeclaration(node)) {
      return [{ name: isDefault ? "default" : node.name?.text, kind: "function", signature: signatureFor(node.parameters, node.type) }];
    }
    if (ts.isVariableStatement(node)) return node.declarationList.declarations.flatMap(declaration => {
      if (!ts.isIdentifier(declaration.name)) return [];
      const value = declaration.initializer;
      const callable = value && (ts.isArrowFunction(value) || ts.isFunctionExpression(value));
      return [{ name: declaration.name.text, kind: callable ? "function" : "value",
        signature: callable ? signatureFor(value.parameters, value.type) : null }];
    });
    return node.name ? [{ name: isDefault ? "default" : node.name.text,
      kind: ts.isInterfaceDeclaration(node) ? "interface" : ts.isTypeAliasDeclaration(node) ? "type" : ts.isClassDeclaration(node) ? "class" : "declaration",
      signature: null }] : [];
  }).filter(item => typeof item.name === "string").map(item => ({
    ...item, signature: item.signature?.replace(/\s+/g, " ").slice(0, 800) || null,
  }));
}

for (const [id, path, module, , , tier] of files) {
  const current = git("show", `${revision}:${path}`);
  const source = /\.(?:tsx?|[cm]?js)$/.test(path) ? ts.createSourceFile(path, current, ts.ScriptTarget.Latest, true) : null;
  const dependencies = source?.statements.flatMap(statement => {
    if (!(ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement))) return [];
    const specifier = statement.moduleSpecifier;
    if (!specifier || !ts.isStringLiteral(specifier)) return [];
    const name = specifier.text;
    if (!/^(?:[\w@.-]+\/)*[\w@.:-]+$/.test(name)) return [];
    if (!name.startsWith(".")) return [name];
    const candidate = posix.normalize(posix.join(dirname(path), name));
    return [paths.has(candidate.replace(/\.js$/, ".ts")) ? candidate.replace(/\.js$/, ".ts") : candidate];
  }) ?? [];
  const modified = git("log", "-1", "--format=%cI", revision, "--", path).trim() || timestamp;
  filesByPath.set(path, { route: routes.get(id), path, module, tier, revision, last_modified: new Date(modified).toISOString(),
    exports: declareExports(source, path), dependencies: [...new Set(dependencies)], dependents: [], mcp_allowed: !protectedPath(path) });
}

for (const item of filesByPath.values()) {
  for (const dependency of item.dependencies) filesByPath.get(dependency)?.dependents.push(item.path);
}

const output = new URL("../src/introspection/catalog.generated.ts", import.meta.url);
const data = "// Generated by scripts/generate-reflection.mjs.\nimport type { ReflectionEntry } from './types.js';\n\nexport const reflectionCatalog: readonly ReflectionEntry[] = [\n" +
  [...filesByPath.values()].map(entry => "  " + JSON.stringify(entry)).join(",\n") + "\n];\n";
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== data) throw new Error("Reflection catalog is out of sync");
} else {
  writeFileSync(output, data);
}
