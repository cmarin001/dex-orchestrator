import assert from "node:assert/strict";
import { test } from "node:test";
import { z } from "zod";
import { defaultRisk } from "../../schemas/risk-config.js";
import { ReconCache } from "../../src/cache/recon-cache.js";
import { Inbox, ControlConflict } from "../../src/control/commands.js";
import { WorkerControls } from "../../src/control/worker.js";
import { fileAudit, readJournal } from "../../src/logging/logger.js";
import { controlFixture, config, target } from "../control-fixture.js";

test("worker applies validated, attributed commands and replays durable rejections and pause state", async t => {
  const f = await controlFixture(t);
  await assert.rejects(f.control.submit("risk",{config:{...config,max_slippage_bps:-1}},"desk"), z.ZodError);
  assert.deepEqual((await f.control.risk()).config,defaultRisk);
  const pause = {request_id:"shared-pause"};
  const receipts = await Promise.all([f.control.submit("pause",pause,"desk"),f.control.submit("pause",pause,"desk")]);
  assert.deepEqual(receipts.map(e=>e.state),["queued","queued"]);
  await assert.rejects(f.control.submit("resume",pause,"desk"),ControlConflict);
  assert.equal(f.worker.paused,false);
  await f.drain();
  assert.equal(f.worker.paused,true);
  assert.equal((await f.control.submit("pause",pause,"desk")).state,"applied");
  await f.control.submit("resume",{},"desk");
  await f.control.submit("risk",{config},"desk");
  await f.control.submit("reject",{token:target.token,chain:target.chain},"desk");
  assert.equal(f.cache.isRejected(target),false);
  await f.drain();
  await f.drain();
  assert.equal(f.worker.paused,false);
  assert.deepEqual((await f.control.risk()).config,config);
  assert.equal((await f.control.risk()).actor,"desk");
  assert.equal(f.cache.isRejected(target),true);
  const cache = new ReconCache();
  const restarted = new WorkerControls(new Inbox(f.paths.inboxPath),f.paths.riskPath,cache,fileAudit(f.paths.auditPath));
  const rows = await readJournal(f.paths.auditPath);
  for(const row of rows) restarted.replay(row);
  assert.equal(restarted.paused,false);
  assert.equal(cache.isRejected({...target,pair:"another-pair"}),true);
  assert.equal(rows.filter(e => e.stage === "control").length,4);
});
